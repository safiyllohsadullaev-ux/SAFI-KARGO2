const dictionaries = { tj, ru, en };

type I18nValue = { lang: Lang; setLang: (lang: Lang) => void; t: (key: string) => string };

const I18nContext = createContext<I18nValue>({ lang: "tj", setLang: () => undefined, t: (key) => key });

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("tj");
  useEffect(() => {
    const saved = localStorage.getItem("safi_lang");
    if (saved === "ru" || saved === "en" || saved === "tj") setLangState(saved);
  }, []);
  const setLang = (next: Lang) => {
    setLangState(next);
    localStorage.setItem("safi_lang", next);
  };
  const value = useMemo<I18nValue>(() => {
    const table = dictionaries[lang];
    return {
      lang,
      setLang,
      t: (key: string) => table[key] || tj[key] || key,
    };
  }, [lang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}

export function pick(value: unknown, lang: Lang) {
  if (!value) return "";
  if (typeof value === "string") return value;
  const row = value as Record<string, string>;
  return row[lang] || row.tj || row.ru || row.en || "";
}

